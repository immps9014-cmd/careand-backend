<?php

namespace App\Support;

/** 주소·지역 문자열 → 시·도 짧은 이름(서울·경기·충북 …). 지역 공지 대상 판정용(CAREN-REF-01 3단계). */
class SidoName
{
    public const ALL = ['서울', '경기', '인천', '부산', '대구', '대전', '광주', '울산', '세종', '강원', '충북', '충남', '전북', '전남', '경북', '경남', '제주'];

    private const LONG = [
        '서울특별시' => '서울', '서울시' => '서울', '경기도' => '경기', '인천광역시' => '인천', '인천시' => '인천', '부산광역시' => '부산', '부산시' => '부산',
        '대구광역시' => '대구', '대구시' => '대구', '대전광역시' => '대전', '대전시' => '대전', '광주광역시' => '광주', '울산광역시' => '울산', '울산시' => '울산',
        '세종특별자치시' => '세종', '세종시' => '세종', '강원도' => '강원', '강원특별자치도' => '강원', '충청북도' => '충북', '충청남도' => '충남',
        '전라북도' => '전북', '전북특별자치도' => '전북', '전라남도' => '전남', '경상북도' => '경북', '경상남도' => '경남', '제주도' => '제주', '제주특별자치도' => '제주',
    ];

    public static function of(?string $text): ?string
    {
        $first = trim(explode(' ', trim((string) $text))[0] ?? '');
        if ($first === '') {
            return null;
        }
        if (in_array($first, self::ALL, true)) {
            return $first;
        }

        return self::LONG[$first] ?? null;
    }
}
